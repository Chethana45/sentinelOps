#!/usr/bin/env bash
# =============================================================================
# SentinelOps - Alertmanager Config Generator
# =============================================================================
# Alertmanager itself does not support runtime environment variable expansion
# in its YAML configuration. This script reads your root .env file and renders
# alertmanager/alertmanager.yml securely before Alertmanager starts or reloads.
#
# If SMTP credentials are not configured, it generates safe fallback routes
# and keeps email alerting optional without breaking the deployment.
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$PROJECT_DIR/.env"
OUTPUT_FILE="$PROJECT_DIR/alertmanager/alertmanager.yml"

# Source .env if it exists (without overriding existing environment variables)
if [ -f "$ENV_FILE" ]; then
    while IFS='=' read -r key value || [ -n "$key" ]; do
        # Ignore comments and blank lines
        case "$key" in
            \#*|"") continue ;;
        esac
        # Strip potential leading/trailing whitespace and surrounding quotes
        key=$(echo "$key" | xargs)
        value=$(echo "$value" | xargs)
        value="${value%\"}"
        value="${value#\"}"
        value="${value%\'}"
        value="${value#\'}"
        # Set only if not already set in the environment
        if [ -z "${!key:-}" ]; then
            export "$key=$value"
        fi
    done < "$ENV_FILE"
fi

SMTP_HOST="${SMTP_HOST:-}"
SMTP_PORT="${SMTP_PORT:-587}"
SMTP_USERNAME="${SMTP_USERNAME:-}"
SMTP_PASSWORD="${SMTP_PASSWORD:-}"
SMTP_FROM="${SMTP_FROM:-}"
ALERT_EMAIL_TO="${ALERT_EMAIL_TO:-}"

# Check if email alerting is enabled (requires host, from, to)
EMAIL_ENABLED=false
if [ -n "$SMTP_HOST" ] && [ -n "$SMTP_FROM" ] && [ -n "$ALERT_EMAIL_TO" ]; then
    EMAIL_ENABLED=true
fi

echo "Generating Alertmanager configuration..."
echo "Email alerts enabled: $EMAIL_ENABLED"

cat <<EOF > "$OUTPUT_FILE"
# =============================================================================
# Alertmanager Configuration — Auto-generated by scripts/generate_alertmanager_config.sh
# =============================================================================
# Do not edit this file directly if you manage variables via .env.
# Update .env and run: bash scripts/generate_alertmanager_config.sh
# =============================================================================

global:
  resolve_timeout: 5m
EOF

if [ "$EMAIL_ENABLED" = true ]; then
cat <<EOF >> "$OUTPUT_FILE"
  smtp_smarthost: '${SMTP_HOST}:${SMTP_PORT}'
  smtp_from: '${SMTP_FROM}'
  smtp_auth_username: '${SMTP_USERNAME}'
  smtp_auth_password: '${SMTP_PASSWORD}'
  smtp_require_tls: true
EOF
fi

cat <<'EOF' >> "$OUTPUT_FILE"

# ---------------------------------------------------------------------------
# Templates
# ---------------------------------------------------------------------------
templates:
  - '/etc/alertmanager/templates/*.tmpl'

# ---------------------------------------------------------------------------
# Routing Tree
# ---------------------------------------------------------------------------
route:
  receiver: 'warning-notifications'
  group_by: ['alertname', 'severity', 'instance']
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h

  routes:
    # -----------------------------------------------------------------------
    # CRITICAL ALERTS: Service Down, Critical CPU/Memory/Disk
    # Immediate notification, frequent repetition
    # -----------------------------------------------------------------------
    - match:
        severity: critical
      receiver: 'critical-notifications'
      group_wait: 10s
      group_interval: 1m
      repeat_interval: 1h
      continue: false

    # -----------------------------------------------------------------------
    # WARNING ALERTS: High CPU/Memory/Disk/Load/Network
    # Standard grouping and timing
    # -----------------------------------------------------------------------
    - match:
        severity: warning
      receiver: 'warning-notifications'
      group_wait: 30s
      group_interval: 5m
      repeat_interval: 4h

    # -----------------------------------------------------------------------
    # TEST ALERTS: Pipeline validation
    # -----------------------------------------------------------------------
    - match:
        severity: test
      receiver: 'test-receiver'
      group_wait: 5s
      group_interval: 1m
      repeat_interval: 1h

# ---------------------------------------------------------------------------
# Inhibition Rules
# ---------------------------------------------------------------------------
# Suppress lower severity alerts when higher severity ones are active
inhibit_rules:
  - source_match:
      alertname: 'InstanceDown'
      severity: 'critical'
    target_match_re:
      alertname: '.*(Cpu|Memory|Disk|Network|Load).*'
    equal: ['instance']

  - source_match:
      severity: 'critical'
    target_match:
      severity: 'warning'
    equal: ['alertname', 'instance']

# ---------------------------------------------------------------------------
# Receivers
# ---------------------------------------------------------------------------
receivers:
  # -------------------------------------------------------------------------
  # Critical Notifications: Paged/emailed to ops with high priority
  # -------------------------------------------------------------------------
  - name: 'critical-notifications'
    webhook_configs:
      - url: 'http://localhost:5001/alerts/critical'
        send_resolved: true
EOF

if [ "$EMAIL_ENABLED" = true ]; then
cat <<EOF >> "$OUTPUT_FILE"
    email_configs:
      - to: '${ALERT_EMAIL_TO}'
        send_resolved: true
        html: '{{ template "email.sentinelops.html" . }}'
        headers:
          subject: '[CRITICAL ALERT] {{ .GroupLabels.alertname }} on {{ .GroupLabels.instance }}'
EOF
fi

cat <<'EOF' >> "$OUTPUT_FILE"

  # -------------------------------------------------------------------------
  # Warning Notifications: General system warnings
  # -------------------------------------------------------------------------
  - name: 'warning-notifications'
    webhook_configs:
      - url: 'http://localhost:5001/alerts'
        send_resolved: true
EOF

if [ "$EMAIL_ENABLED" = true ]; then
cat <<EOF >> "$OUTPUT_FILE"
    email_configs:
      - to: '${ALERT_EMAIL_TO}'
        send_resolved: true
        html: '{{ template "email.sentinelops.html" . }}'
        headers:
          subject: '[WARNING] {{ .GroupLabels.alertname }} on {{ .GroupLabels.instance }}'
EOF
fi

cat <<'EOF' >> "$OUTPUT_FILE"

  # -------------------------------------------------------------------------
  # Test Receiver: For synthetic / pipeline testing (webhooks only)
  # -------------------------------------------------------------------------
  - name: 'test-receiver'
    webhook_configs:
      - url: 'http://localhost:5001/alerts/test'
        send_resolved: true
EOF

echo "Alertmanager configuration generated successfully at $OUTPUT_FILE"
